/* symmetric eigenvalue routine (Jacobi), for the PSD check of the Gram blocks */
static void jacobi(int n, const double *A, double *ev) {
    double a[100]; for (int i=0;i<n*n;i++) a[i]=A[i];
    for (int sweep=0; sweep<100; sweep++) {
        double off=0; for (int p=0;p<n;p++) for (int q=p+1;q<n;q++) off+=a[p*n+q]*a[p*n+q];
        if (off < 1e-28) break;
        for (int p=0;p<n;p++) for (int q=p+1;q<n;q++) {
            double apq=a[p*n+q]; if (fabs(apq)<1e-300) continue;
            double th=(a[q*n+q]-a[p*n+p])/(2*apq);
            double t=(th>=0?1:-1)/(fabs(th)+sqrt(th*th+1));
            double c=1/sqrt(t*t+1), s=t*c;
            for (int k=0;k<n;k++){double ap=a[p*n+k],aq=a[q*n+k];a[p*n+k]=c*ap-s*aq;a[q*n+k]=s*ap+c*aq;}
            for (int k=0;k<n;k++){double ap=a[k*n+p],aq=a[k*n+q];a[k*n+p]=c*ap-s*aq;a[k*n+q]=s*ap+c*aq;}
        }
    }
    for (int i=0;i<n;i++) ev[i]=a[i*n+i];
}

static int solve_feas(double rho, double *QS, double *QL) {
    PRIMALenv_t env; PRIMALtask_t t;
    PRIMAL_makeenv(&env, NULL); PRIMAL_maketask(env, 0, 0, &t);
    int dims[2] = {10, 6};
    PRIMAL_appendbarvars(t, 2, dims);
    PRIMAL_appendcons(t, NROW);
    for (int r = 0; r < NROW; r++) {
        int si[NTRIS], sj[NTRIS]; double sv[NTRIS]; int n = 0, id;
        for (int k = 0; k < NTRIS; k++) { int i=TS[k][0], j=TS[k][1];
            double v = AS[r][k] * ((i==j)?1.0:0.5);
            if (v != 0.0) { si[n]=i; sj[n]=j; sv[n]=v; n++; } }
        if (n > 0) { PRIMAL_appendsparsesymmat(t, 10, n, si, sj, sv, &id);
                      PRIMAL_putbaraij(t, r, 0, 1, &id, (double[]){1.0}); }
        n = 0;
        for (int k = 0; k < NTRIL; k++) { int i=TL[k][0], j=TL[k][1];
            double v = (rho*AL[r][k] - ALV[r][k]) * ((i==j)?1.0:0.5);
            if (v != 0.0) { si[n]=i; sj[n]=j; sv[n]=v; n++; } }
        if (n > 0) { PRIMAL_appendsparsesymmat(t, 6, n, si, sj, sv, &id);
                      PRIMAL_putbaraij(t, r, 1, 1, &id, (double[]){1.0}); }
        PRIMAL_putconbound(t, r, PRIMAL_BK_FX, RHS[r], RHS[r]);
    }
    PRIMALrescodee rc = PRIMAL_optimize(t);
    int ok = (rc == PRIMAL_RES_OK);
    if (ok) { PRIMAL_getbarxj(t, PRIMAL_SOL_ITR, 0, QS); PRIMAL_getbarxj(t, PRIMAL_SOL_ITR, 1, QL); }
    PRIMAL_deletetask(&t); PRIMAL_deleteenv(&env);
    return ok;
}

