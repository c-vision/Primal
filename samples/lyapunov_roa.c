/* lyapunov_roa.c - SOS Lyapunov region-of-attraction certificate, from the
 * "lyapunov-toolbox" project (https://github.com/Ali-Eimaan/lyapunov-toolbox,
 * BSD-3-Clause), solved with this library.
 *
 * Time-reversed Van der Pol oscillator  x1' = -x2,  x2' = x1 + (x1^2-1) x2,
 * with the quadratic Lyapunov function from the linearisation,
 *   V(x) = 1.5 x1^2 - x1 x2 + x2^2.
 * The certified sublevel set Omega_rho = {V <= rho} is proved invariant by the
 * SOS S-procedure certificate (Putinar multiplier lambda in SOS):
 *   -(Vdot + eps*||x||^4) + lambda * (V - rho)  in  Sigma[x].
 * With lambda = z2' QL z2 (basis z2 of degree <= 2) and the expression written as
 * z3' QS z3 (basis z3 of degree <= 3), this is an SDP: QS >= 0 (10x10),
 * QL >= 0 (6x6), plus one linear equality per monomial (28 rows).
 *
 * The data below (AS, AL, ALV, RHS) is the exact coefficient table of that
 * identity; Mc = rho*AL - ALV depends on rho.  The certified level is found by
 * bisection; the repo reports rho = 2.304375 (Julia) / 2.316 (MATLAB), and the
 * true tangency level is min V on {Vdot = 0} = 2.30448.
 *
 * Usage: lyapunov_roa   (no arguments)
 */
