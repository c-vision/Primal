def jacobi(n, mat):
    """Eigenvalues of a symmetric n x n matrix (cyclic Jacobi, as the C example)."""
    a = list(mat[:n * n])
    for _ in range(100):
        off = 0.0
        for p in range(n):
            for q in range(p + 1, n):
                off += a[p * n + q] * a[p * n + q]
        if off < 1e-28:
            break
        for p in range(n):
            for q in range(p + 1, n):
                apq = a[p * n + q]
                if abs(apq) < 1e-300:
                    continue
                th = (a[q * n + q] - a[p * n + p]) / (2 * apq)
                t = (1 if th >= 0 else -1) / (abs(th) + math.sqrt(th * th + 1))
                c = 1 / math.sqrt(t * t + 1)
                s = t * c
                for k in range(n):
                    ap, aq = a[p * n + k], a[q * n + k]
                    a[p * n + k] = c * ap - s * aq
                    a[q * n + k] = s * ap + c * aq
                for k in range(n):
                    ap, aq = a[k * n + p], a[k * n + q]
                    a[k * n + p] = c * ap - s * aq
                    a[k * n + q] = s * ap + c * aq
    return [a[i * n + i] for i in range(n)]


def solve_feas(rho):
    """SOS feasibility of the Lyapunov certificate at level rho; returns (ok, QS, QL)."""
    with Model() as m:
        m.barvars([10, 6])
        m.add_cons(NROW)
        for r in range(NROW):
            terms = [(TS[k][0], TS[k][1], AS[r][k] * (1.0 if TS[k][0] == TS[k][1] else 0.5))
                     for k in range(NTRIS)]
            terms = [t for t in terms if t[2] != 0.0]
            if terms:
                m.baraij(r, 0, [(m.sparsesymmat(10, terms), 1.0)])
            terms = [(TL[k][0], TL[k][1], (rho * AL[r][k] - ALV[r][k]) * (1.0 if TL[k][0] == TL[k][1] else 0.5))
                     for k in range(NTRIL)]
            terms = [t for t in terms if t[2] != 0.0]
            if terms:
                m.baraij(r, 1, [(m.sparsesymmat(6, terms), 1.0)])
            m.con_bounds(r, BK.FX, RHS[r], RHS[r])
        res = m.solve()
        if res.rc != 0:
            return False, None, None
        return True, m.getbarxj(0), m.getbarxj(1)


def main() -> int:
    lo, hi = 0.0, 4.0                               # bisection on the certified level
    for _ in range(26):
        mid = 0.5 * (lo + hi)
        if solve_feas(mid)[0]:
            lo = mid
        else:
            hi = mid
    ok = 2.30 < lo < 2.31
    feas, qs, ql = solve_feas(lo)                   # certificate at the certified level
    if not feas:
        print("lyapunov_roa  certificate solve failed")
        return 1
    mns = min(jacobi(10, qs))                       # Gram blocks PSD and identity holds
    mnl = min(jacobi(6, ql))
    ids = 0.0                                       # identity residual: AS vech(QS) + Mc vech(QL) - RHS
    for r in range(NROW):
        acc = 0.0
        for k in range(NTRIS):
            acc += AS[r][k] * qs[TS[k][0] * 10 + TS[k][1]]
        for k in range(NTRIL):
            acc += (lo * AL[r][k] - ALV[r][k]) * ql[TL[k][0] * 6 + TL[k][1]]
        ids = max(ids, abs(acc - RHS[r]))
    ok = ok and mns > -1e-6 and mnl > -1e-6 and ids < 1e-6
    print(f"lyapunov_roa  rho={lo:.6f}  (repo 2.304375, true tangency 2.30448)")
    print(f"              Gram PSD: min eig QS={mns:.3e} QL={mnl:.3e}  identity residual={ids:.3e}  "
          f"{'OK' if ok else 'FAIL'}")
    return 0 if ok else 1


